"""Regenerate packages/core/src/whatsapp/rate-card.ts from Meta's WhatsApp rate cards (docs/runbooks/whatsapp.md).

  python -I scripts/whatsapp/rate-card.py <cards dir> <markets.tsv> <effective date YYYY-MM-DD>

<cards dir>: Meta's "list rates" file for each billing currency, saved as <CUR>_list_rates.xlsx (the links on
developers.facebook.com/docs/whatsapp/pricing are signed and expire; Meta names them .csv but they are Excel files).
<markets.tsv>: ISO code <TAB> market, one line per country in the docs page's "Pricing regions on the rate card"
table (a regional country's market is its region, e.g. "Rest of Africa"). Standard library only; reads data only.
"""
import json, os, re, sys, zipfile
import xml.etree.ElementTree as ET

M = "{http://schemas.openxmlformats.org/spreadsheetml/2006/main}"


def rows(path):
    z = zipfile.ZipFile(path)
    shared = []
    if "xl/sharedStrings.xml" in z.namelist():
        for si in ET.fromstring(z.read("xl/sharedStrings.xml")).iter(M + "si"):
            shared.append("".join(t.text or "" for t in si.iter(M + "t")))
    sheet = sorted(n for n in z.namelist() if n.startswith("xl/worksheets/sheet"))[0]
    for r in ET.fromstring(z.read(sheet)).iter(M + "row"):
        vals = {}
        for c in r.iter(M + "c"):
            col = re.match(r"[A-Z]+", c.get("r")).group(0)
            v, t = c.find(M + "v"), c.get("t")
            if t == "inlineStr":
                vals[col] = "".join(x.text or "" for x in c.iter(M + "t"))
            elif v is not None:
                vals[col] = shared[int(v.text)] if t == "s" else v.text
        yield vals


def card(path):
    out, cols = {}, None
    for r in rows(path):
        if cols is None:
            if (r.get("A") or "").strip() == "Market":
                cols = {re.sub(r"\s+", "", v): k for k, v in r.items() if v}
            continue
        market = (r.get(cols["Market"]) or "").strip()
        if market:
            out[market] = [float(r[cols[k]]) for k in ("Marketing", "Utility", "Authentication")]
    return out


def num(x):
    return ("%.6f" % x).rstrip("0").rstrip(".") or "0"


def main(cards_dir, markets_tsv, date):
    cards = {f.split("_")[0]: card(os.path.join(cards_dir, f)) for f in sorted(os.listdir(cards_dir)) if f.endswith("_list_rates.xlsx")}
    markets = [line.split("\t") for line in open(markets_tsv, encoding="utf-8").read().splitlines() if line.strip()]
    names = list(cards["USD"])
    assert all(list(c) == names for c in cards.values()), "every card must list the same markets"
    assert {m for _, m in markets} <= set(names), "a country maps to a market the cards don't price"
    o = [
        "// GENERATED by scripts/whatsapp/rate-card.py from Meta's WhatsApp Business Platform rate cards (list rates, one",
        "// file per billing currency, developers.facebook.com/docs/whatsapp/pricing). Meta changes prices only on Jan 1,",
        "// Apr 1, Jul 1 and Oct 1: to refresh, see docs/runbooks/whatsapp.md (\"Meta's rate card\"). Do not edit by hand.",
        "",
        "/** The day the cards below took effect. */",
        f'export const RATE_CARD_DATE = "{date}";',
        "",
        "/**",
        " * Meta's markets, by the recipient's country (ISO 3166 alpha-2, as LUME reads it from the phone number). A country",
        ' * not listed is "Other".',
        " */",
        "export const MARKET_OF: Readonly<Record<string, string>> = {",
        *[f"  {iso}: {json.dumps(m)}," for iso, m in sorted(markets)],
        "};",
        "",
        "/** Each currency Meta bills in: per market, one message's [marketing, utility, authentication] list rate. */",
        "export const RATE_CARDS: Readonly<Record<string, Readonly<Record<string, readonly [number, number, number]>>>> = {",
    ]
    for cur in sorted(cards):
        o.append(f"  {cur}: {{")
        o += [f"    {json.dumps(m)}: [{', '.join(num(x) for x in cards[cur][m])}]," for m in names]
        o.append("  },")
    o.append("};")
    target = os.path.join(os.path.dirname(__file__), "..", "..", "packages", "core", "src", "whatsapp", "rate-card.ts")
    open(target, "w", newline="\n").write("\n".join(o) + "\n")
    print(f"{len(cards)} currencies, {len(names)} markets, {len(markets)} countries -> {os.path.normpath(target)}")


if __name__ == "__main__":
    main(*sys.argv[1:4])
